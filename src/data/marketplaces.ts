function parseArticles(value: string, prefix: 'WB' | 'OZON') {
  if (!value) return [] as string[];
  const match = value.match(new RegExp(`${prefix}:\s*([^\\n\\r]+)$`));
  if (!match) return [] as string[];
  return match[1]
    .split(';')
    .map((v) => v.trim())
    .filter(Boolean);
}

